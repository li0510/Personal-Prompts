PHILOSOPHY_1: str = """
哲学一：产品设计与输出标准

产品产出的每一行代码，必须通过注释规范、格式统一、输出完整、
质量保障的标准体系。代码经得起标准模板的逐项对照。

—— 全局类标准 ——

1. 用户分层设计原则
   - 面向不同用户群体的同一功能，必须提供各自独立且完整的形态
   - 不允许混用形态，不允许简化任一形态

2. 不可逆操作防御原则
   - 所有不可逆操作必须设置至少一道缓冲防线
   - 防线层级：二次确认 → 可恢复中间态 → 彻底删除
   - 可恢复中间态行为对齐主流操作系统标准

3. 最小验证前置原则
   - 大规模实施前必须先构建最小化验证单元
   - 以最小成本、最简步骤验证方案设计与可行性

4. 零外部依赖原则
   - 所有外部依赖必须本地化，确保离线环境可用
   - 全流程可固化可反复重复使用

—— 局部类标准：前端 ——

5. 设计系统基座锁定原则
   - 前端 UI 必须基于单一成熟设计系统构建
   - 禁止混用其他设计系统，禁止自行发明新样式

6. 外部参考范围约束原则
   - 明确划定可借鉴与禁止借鉴的外部参考范围

—— 局部类标准：前端代码质量 ——

7. 前端代码质量原则
   - 前端代码与后端代码同等质量标准
   - 禁止硬编码、职责混乱、命名不一致、代码重复、无效 CSS
"""


PHILOSOPHY_1: str = """
哲学一：框架设计与输出标准

框架产出的每一行代码，必须通过注释规范、格式统一、输出完整、
质量保障的标准体系。代码经得起标准模板的逐项对照。

体现：P32（中文注释）、P33（完整可运行文件）、
      P39（代码输出标准）、P40（全局一致性）、
      P42（对话框拆分）、Debug 模式十步流程

—— 框架全局类标准 ——

1. 用户分层设计原则
   - 面向不同用户群体的同一功能，必须提供各自独立且完整的形态
   - 不允许混用两种形态，不允许简化任一形态
   - 后端：CLI 模式 vs Web 模式
   - 前端：业务用户模式 vs 技术用户模式

2. 不可逆操作防御原则
   - 所有不可逆操作必须设置至少一道缓冲防线
   - 防线层级：二次确认弹窗 → 可恢复中间态 → 彻底删除
   - 可恢复中间态行为对齐主流操作系统（Windows/macOS）标准
   - 适用于：文件删除、数据库操作、配置覆盖等所有不可逆操作

3. 最小验证前置原则
   - 大规模实施前必须先构建最小化验证单元
   - 以最小成本、最简步骤验证方案设计与可行性
   - 适用于任何模块的新建或重构

4. 零外部依赖原则
   - 所有外部依赖必须本地化，确保离线环境可用
   - 全流程可固化可反复重复使用
   - 全流程稳定性最高规格
   - 全流程安全性最高规格
   - 适用于：后端 Python 依赖 + 前端 JS/CSS 依赖

—— 框架局部类标准：前端 ——

5. 设计系统基座锁定原则
   - 前端 UI 界面必须基于单一成熟设计系统构建
   - 所有组件样式、布局结构、交互模式严格对齐该设计系统
   - 禁止混用其他设计系统，禁止自行发明新样式

6. 外部参考范围约束原则
   - 明确划定可借鉴与禁止借鉴的外部参考范围
   - 可借鉴部分仅限于经确认的特定功能模块
   - 禁止借鉴布局、配色、组件样式等其他任何部分

—— 框架局部类标准：前端代码质量 [UPDATED] ——

7. 前端代码质量原则
   - 前端代码与后端代码同等质量标准
   - 禁止硬编码：所有配置参数必须从统一配置源读取
   - 禁止职责混乱：每个函数承担单一明确职责
   - 禁止命名不一致：同一概念在整个前端代码中使用统一术语
   - 禁止代码重复：相同逻辑必须提取为公共函数
   - 禁止无效 CSS：HTML 中使用的每个 class 必须在 CSS 中有对应定义
   - 禁止错误信息误导：异常捕获的错误信息必须与实际根因一致
"""

